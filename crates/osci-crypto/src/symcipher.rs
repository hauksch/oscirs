//! Streaming symmetric ciphers over the OSCI wire format
//! (port of `SymCipherOutputStream` / `SymCipherInputStream`):
//! `[IV][ciphertext]` where CBC adds PKCS#7 padding and GCM appends the
//! 128-bit tag.
//!
//! GCM is implemented from primitives (`aes` + `ctr` + `ghash`) so both
//! directions stay streaming; the tag is verified when the reader reaches
//! the end of the stream. GHASH always runs over the ciphertext.

use std::io::{self, Read, Write};

use aes::cipher::{BlockEncrypt, KeyInit, KeyIvInit};
use aes::{Aes128, Aes192, Aes256, Block};
use des::TdesEde3;
use ghash::universal_hash::UniversalHash as _;
use rand::RngCore;

use crate::algorithms::SymCipher;
use crate::error::CryptoError;

const GCM_TAG_LEN: usize = 16;

// ---------------------------------------------------------------- GCM core

enum AesCore {
    Aes128(Box<Aes128>),
    Aes192(Box<Aes192>),
    Aes256(Box<Aes256>),
}

impl AesCore {
    fn new(key: &[u8]) -> Result<Self, CryptoError> {
        Ok(match key.len() {
            16 => Self::Aes128(Box::new(Aes128::new_from_slice(key).unwrap())),
            24 => Self::Aes192(Box::new(Aes192::new_from_slice(key).unwrap())),
            32 => Self::Aes256(Box::new(Aes256::new_from_slice(key).unwrap())),
            n => return Err(CryptoError::InvalidKey(format!("AES key of {n} bytes"))),
        })
    }

    fn encrypt_block(&self, block: &mut [u8; 16]) {
        let mut generic = Block::from(*block);
        match self {
            Self::Aes128(c) => c.encrypt_block(&mut generic),
            Self::Aes192(c) => c.encrypt_block(&mut generic),
            Self::Aes256(c) => c.encrypt_block(&mut generic),
        }
        *block = generic.into();
    }
}

/// GCM state: CTR keystream from inc32(J0) plus GHASH over
/// (AAD = empty, IV, ciphertext). The keystream is generated by encrypting
/// the running counter block (GCM's CTR mode).
struct Gcm {
    aes: AesCore,
    counter: [u8; 16],
    /// Current keystream block and how many of its bytes were consumed;
    /// GCM's CTR keystream is continuous across process() calls.
    ks_block: [u8; 16],
    ks_offset: usize,
    ghash: ghash::GHash,
    /// Partial GHASH block (< 16 bytes) carried across process() calls;
    /// `update_padded` may only run once over the whole message tail.
    ghash_tail: Vec<u8>,
    /// Enc(J0), XORed into the final GHASH output.
    ej0: [u8; 16],
    ciphertext_bits: u64,
    finished: bool,
}

impl Gcm {
    fn new(key: &[u8], iv: &[u8]) -> Result<Self, CryptoError> {
        let aes = AesCore::new(key)?;
        let mut h = [0u8; 16];
        aes.encrypt_block(&mut h);
        let ghash = ghash::GHash::new(ghash::Key::from_slice(&h));

        let (j0, ej0) = match iv.len() {
            12 => {
                let mut j0 = [0u8; 16];
                j0[..12].copy_from_slice(iv);
                j0[15] = 1;
                let mut ej0 = j0;
                aes.encrypt_block(&mut ej0);
                (j0, ej0)
            }
            n => {
                let mut ghash = ghash::GHash::new(ghash::Key::from_slice(&h));
                for chunk in iv.chunks(16) {
                    let mut block = [0u8; 16];
                    block[..chunk.len()].copy_from_slice(chunk);
                    ghash.update_padded(&block);
                }
                let mut block = [0u8; 16];
                block[8..].copy_from_slice(&((n as u64) * 8).to_be_bytes());
                ghash.update_padded(&block);
                let j0 = ghash.finalize();
                let mut j0_arr = [0u8; 16];
                j0_arr.copy_from_slice(j0.as_slice());
                let mut ej0 = j0_arr;
                aes.encrypt_block(&mut ej0);
                (j0_arr, ej0)
            }
        };

        let mut counter = j0;
        inc32(&mut counter);
        Ok(Self {
            aes,
            counter,
            ks_block: [0u8; 16],
            ks_offset: 0,
            ghash,
            ghash_tail: Vec::new(),
            ej0,
            ciphertext_bits: 0,
            finished: false,
        })
    }

    /// GHASH the ciphertext, then apply the keystream (decrypt direction).
    fn process(&mut self, data: &mut [u8]) {
        self.absorb_ghash(data);
        self.keystream(data);
    }

    /// Keystream first (encrypt direction), then GHASH the ciphertext.
    fn encrypt_chunk(&mut self, data: &mut [u8]) {
        self.keystream(data);
        self.absorb_ghash(data);
    }

    /// GHASH full blocks immediately; carry a partial block to the next
    /// call so padding happens exactly once at the end of the message.
    fn absorb_ghash(&mut self, data: &[u8]) {
        self.ciphertext_bits = self.ciphertext_bits.wrapping_add((data.len() as u64) * 8);
        self.ghash_tail.extend_from_slice(data);
        while self.ghash_tail.len() >= 16 {
            let block: [u8; 16] = self.ghash_tail[..16].try_into().unwrap();
            self.ghash.update_padded(&block);
            self.ghash_tail.drain(..16);
        }
    }

    fn keystream(&mut self, data: &mut [u8]) {
        let mut i = 0;
        while i < data.len() {
            if self.ks_offset == 0 {
                self.ks_block = self.counter;
                self.aes.encrypt_block(&mut self.ks_block);
            }
            let take = (16 - self.ks_offset).min(data.len() - i);
            for j in 0..take {
                data[i + j] ^= self.ks_block[self.ks_offset + j];
            }
            self.ks_offset += take;
            i += take;
            if self.ks_offset == 16 {
                self.ks_offset = 0;
                inc32(&mut self.counter);
            }
        }
    }

    fn tag(mut self) -> [u8; 16] {
        self.finished = true;
        if !self.ghash_tail.is_empty() {
            self.ghash.update_padded(&self.ghash_tail);
            self.ghash_tail.clear();
        }
        let mut block = [0u8; 16];
        block[8..].copy_from_slice(&self.ciphertext_bits.to_be_bytes());
        self.ghash.update_padded(&block);
        let s = self.ghash.finalize();
        let mut tag = [0u8; 16];
        for (i, (a, b)) in s.as_slice().iter().zip(self.ej0.iter()).enumerate() {
            tag[i] = a ^ b;
        }
        tag
    }
}

fn inc32(block: &mut [u8; 16]) {
    let mut counter = u32::from_be_bytes(block[12..].try_into().unwrap());
    counter = counter.wrapping_add(1);
    block[12..].copy_from_slice(&counter.to_be_bytes());
}

// ---------------------------------------------------------------- CBC core

enum EncCore {
    Aes128(cbc::Encryptor<Aes128>),
    Aes192(cbc::Encryptor<Aes192>),
    Aes256(cbc::Encryptor<Aes256>),
    Des(cbc::Encryptor<TdesEde3>),
}

impl EncCore {
    /// `block.len()` is the cipher's block size (16 for AES, 8 for 3DES).
    fn encrypt(&mut self, block: &mut [u8]) {
        use aes::cipher::BlockEncryptMut as _;
        match self {
            Self::Aes128(c) => {
                let mut b = Block::clone_from_slice(block);
                c.encrypt_block_mut(&mut b);
                block.copy_from_slice(b.as_slice());
            }
            Self::Aes192(c) => {
                let mut b = Block::clone_from_slice(block);
                c.encrypt_block_mut(&mut b);
                block.copy_from_slice(b.as_slice());
            }
            Self::Aes256(c) => {
                let mut b = Block::clone_from_slice(block);
                c.encrypt_block_mut(&mut b);
                block.copy_from_slice(b.as_slice());
            }
            Self::Des(c) => {
                let mut b = <aes::cipher::generic_array::GenericArray<u8, aes::cipher::typenum::U8>>::clone_from_slice(block);
                c.encrypt_block_mut(&mut b);
                block.copy_from_slice(&b);
            }
        }
    }
}

enum DecCore {
    Aes128(cbc::Decryptor<Aes128>),
    Aes192(cbc::Decryptor<Aes192>),
    Aes256(cbc::Decryptor<Aes256>),
    Des(cbc::Decryptor<TdesEde3>),
}

impl DecCore {
    fn decrypt(&mut self, block: &mut [u8]) {
        use aes::cipher::BlockDecryptMut as _;
        match self {
            Self::Aes128(c) => {
                let mut b = Block::clone_from_slice(block);
                c.decrypt_block_mut(&mut b);
                block.copy_from_slice(b.as_slice());
            }
            Self::Aes192(c) => {
                let mut b = Block::clone_from_slice(block);
                c.decrypt_block_mut(&mut b);
                block.copy_from_slice(b.as_slice());
            }
            Self::Aes256(c) => {
                let mut b = Block::clone_from_slice(block);
                c.decrypt_block_mut(&mut b);
                block.copy_from_slice(b.as_slice());
            }
            Self::Des(c) => {
                let mut b = <aes::cipher::generic_array::GenericArray<u8, aes::cipher::typenum::U8>>::clone_from_slice(block);
                c.decrypt_block_mut(&mut b);
                block.copy_from_slice(&b);
            }
        }
    }
}

struct CbcEncrypt {
    core: EncCore,
    buffer: Vec<u8>,
    block_size: usize,
}

impl CbcEncrypt {
    fn new(cipher: SymCipher, key: &[u8], iv: &[u8]) -> Result<Self, CryptoError> {
        let core = match cipher {
            SymCipher::AesCbc { key_len: 16 } => {
                EncCore::Aes128(cbc::Encryptor::<Aes128>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::AesCbc { key_len: 24 } => {
                EncCore::Aes192(cbc::Encryptor::<Aes192>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::AesCbc { key_len: 32 } => {
                EncCore::Aes256(cbc::Encryptor::<Aes256>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::TripleDesCbc => {
                EncCore::Des(cbc::Encryptor::<TdesEde3>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::AesGcm { .. } => {
                return Err(CryptoError::UnsupportedAlgorithm("GCM in CBC path".into()));
            }
            SymCipher::AesCbc { key_len: n } => {
                return Err(CryptoError::InvalidKey(format!("AES key of {n} bytes")));
            }
        };
        Ok(Self {
            core,
            buffer: Vec::new(),
            block_size: cipher_block_size(cipher),
        })
    }

    fn update(&mut self, data: &[u8], out: &mut Vec<u8>) {
        self.buffer.extend_from_slice(data);
        let blocks = self.buffer.len() / self.block_size;
        for i in 0..blocks {
            let start = i * self.block_size;
            let mut block = self.buffer[start..start + self.block_size].to_vec();
            self.core.encrypt(&mut block);
            out.extend_from_slice(&block);
        }
        self.buffer.drain(..blocks * self.block_size);
    }

    fn finish(&mut self, out: &mut Vec<u8>) {
        let pad = self.block_size - (self.buffer.len() % self.block_size);
        self.buffer.extend(std::iter::repeat_n(pad as u8, pad));
        for chunk in self.buffer.chunks(self.block_size) {
            let mut block = chunk.to_vec();
            self.core.encrypt(&mut block);
            out.extend_from_slice(&block);
        }
    }
}

struct CbcDecrypt {
    core: DecCore,
    pending: Vec<u8>,
    block_size: usize,
    finished: bool,
}

impl CbcDecrypt {
    fn new(cipher: SymCipher, key: &[u8], iv: &[u8]) -> Result<Self, CryptoError> {
        let core = match cipher {
            SymCipher::AesCbc { key_len: 16 } => {
                DecCore::Aes128(cbc::Decryptor::<Aes128>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::AesCbc { key_len: 24 } => {
                DecCore::Aes192(cbc::Decryptor::<Aes192>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::AesCbc { key_len: 32 } => {
                DecCore::Aes256(cbc::Decryptor::<Aes256>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::TripleDesCbc => {
                DecCore::Des(cbc::Decryptor::<TdesEde3>::new_from_slices(key, iv).unwrap())
            }
            SymCipher::AesGcm { .. } => {
                return Err(CryptoError::UnsupportedAlgorithm("GCM in CBC path".into()));
            }
            SymCipher::AesCbc { key_len: n } => {
                return Err(CryptoError::InvalidKey(format!("AES key of {n} bytes")));
            }
        };
        Ok(Self {
            core,
            pending: Vec::new(),
            block_size: cipher_block_size(cipher),
            finished: false,
        })
    }

    /// Decrypt all complete blocks except the newest one (which may carry
    /// padding); the remainder is held until `finish`.
    fn update(&mut self, data: &[u8], out: &mut Vec<u8>) {
        self.pending.extend_from_slice(data);
        let decryptable = self.pending.len() / self.block_size;
        let blocks = decryptable.saturating_sub(1);
        for i in 0..blocks {
            let start = i * self.block_size;
            let mut block = self.pending[start..start + self.block_size].to_vec();
            self.core.decrypt(&mut block);
            out.extend_from_slice(&block);
        }
        self.pending.drain(..blocks * self.block_size);
    }

    fn finish(&mut self, out: &mut Vec<u8>) -> Result<(), CryptoError> {
        if self.finished {
            return Ok(());
        }
        if self.pending.len() != self.block_size {
            return Err(CryptoError::Decryption("truncated CBC stream".into()));
        }
        let mut block = self.pending.clone();
        self.core.decrypt(&mut block);
        let plain = block.as_slice();
        let pad = plain[self.block_size - 1] as usize;
        if pad == 0 || pad > self.block_size {
            return Err(CryptoError::Decryption("bad PKCS#7 padding".into()));
        }
        if plain[self.block_size - pad..] != vec![pad as u8; pad][..] {
            return Err(CryptoError::Decryption("bad PKCS#7 padding".into()));
        }
        out.extend_from_slice(&plain[..self.block_size - pad]);
        self.pending.clear();
        self.finished = true;
        Ok(())
    }
}

fn cipher_block_size(cipher: SymCipher) -> usize {
    match cipher {
        SymCipher::TripleDesCbc => 8,
        _ => 16,
    }
}

// ----------------------------------------------------------------- writers

/// Encrypting writer: emits `[IV][ciphertext (+tag | PKCS#7 padding)]`,
/// exactly like `SymCipherOutputStream`.
pub struct EncryptWriter<'a, W: Write> {
    inner: &'a mut W,
    iv: Vec<u8>,
    mode: EncryptMode,
}

enum EncryptMode {
    Gcm(Box<Gcm>),
    Cbc(Box<CbcEncrypt>),
}

impl<'a, W: Write> EncryptWriter<'a, W> {
    pub fn new(
        inner: &'a mut W,
        cipher: SymCipher,
        key: &[u8],
        iv: Option<&[u8]>,
    ) -> Result<Self, CryptoError> {
        let iv_len = match (cipher, iv) {
            (SymCipher::AesGcm { .. }, Some(custom)) => {
                // GCM IVs are 12 bytes only: the decrypt side always reads
                // 12 (the pre-Korrigenda-7 16-byte IV is not supported, so
                // accepting it on encrypt would produce unreadable output).
                let len = custom.len();
                if len != 12 {
                    return Err(CryptoError::Encryption(format!(
                        "wrong GCM IV length {len} (only 12 is supported)"
                    )));
                }
                len
            }
            (SymCipher::AesGcm { .. }, None) => crate::algorithms::DEFAULT_GCM_IV_LENGTH,
            _ => cipher.iv_length(),
        };
        let iv = iv.map(<[u8]>::to_vec).unwrap_or_else(|| {
            let mut iv = vec![0u8; iv_len];
            rand::thread_rng().fill_bytes(&mut iv);
            iv
        });
        if iv.len() != iv_len {
            return Err(CryptoError::Encryption(format!(
                "IV length {} != expected {iv_len}",
                iv.len()
            )));
        }
        inner.write_all(&iv)?;
        let mode = match cipher {
            SymCipher::AesGcm { .. } => EncryptMode::Gcm(Box::new(Gcm::new(key, &iv)?)),
            SymCipher::AesCbc { .. } | SymCipher::TripleDesCbc => {
                EncryptMode::Cbc(Box::new(CbcEncrypt::new(cipher, key, &iv)?))
            }
        };
        Ok(Self { inner, iv, mode })
    }

    /// The IV written to the stream.
    pub fn iv(&self) -> &[u8] {
        &self.iv
    }

    pub fn finish(mut self) -> io::Result<()> {
        let tail = match &mut self.mode {
            EncryptMode::Gcm(_) => Vec::new(),
            EncryptMode::Cbc(cbc) => {
                let mut tail = Vec::new();
                cbc.finish(&mut tail);
                tail
            }
        };
        let tag = match self.mode {
            EncryptMode::Gcm(gcm) => Some(gcm.tag()),
            EncryptMode::Cbc(_) => None,
        };
        if let Some(tag) = tag {
            self.inner.write_all(&tag)?;
        }
        self.inner.write_all(&tail)?;
        self.inner.flush()
    }
}

impl<W: Write> Write for EncryptWriter<'_, W> {
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        match &mut self.mode {
            EncryptMode::Gcm(gcm) => {
                let mut ciphertext = buf.to_vec();
                gcm.encrypt_chunk(&mut ciphertext);
                self.inner.write_all(&ciphertext)?;
            }
            EncryptMode::Cbc(cbc) => {
                let mut out = Vec::with_capacity(buf.len());
                cbc.update(buf, &mut out);
                self.inner.write_all(&out)?;
            }
        }
        Ok(buf.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        self.inner.flush()
    }
}

/// Decrypting reader over `[IV][ciphertext (+tag | PKCS#7 padding)]`.
/// For GCM, the last 16 bytes are held back as the tag candidate and
/// verified at end of stream.
pub struct DecryptReader<R: Read> {
    inner: R,
    cipher: SymCipher,
    key: Vec<u8>,
    iv_len: usize,
    initialized: bool,
    /// Plaintext buffered for delivery.
    plain: Vec<u8>,
    plain_pos: usize,
    gcm: Option<Gcm>,
    /// GCM tag candidate (last <=16 unread ciphertext bytes).
    gcm_holdback: Vec<u8>,
    cbc: Option<CbcDecrypt>,
    done: bool,
    #[allow(dead_code)]
    iv: Vec<u8>,
}

impl<R: Read> DecryptReader<R> {
    pub fn new(inner: R, cipher: SymCipher, key: &[u8]) -> Result<Self, CryptoError> {
        Ok(Self {
            inner,
            cipher,
            key: key.to_vec(),
            iv_len: cipher.iv_length(),
            initialized: false,
            plain: Vec::new(),
            plain_pos: 0,
            gcm: None,
            gcm_holdback: Vec::new(),
            cbc: None,
            done: false,
            iv: Vec::new(),
        })
    }

    fn initialize(&mut self) -> io::Result<()> {
        if self.initialized {
            return Ok(());
        }
        let mut iv = vec![0u8; self.iv_len];
        let mut filled = 0;
        while filled < self.iv_len {
            match self.inner.read(&mut iv[filled..])? {
                0 => {
                    return Err(io::Error::new(
                        io::ErrorKind::UnexpectedEof,
                        "stream shorter than IV",
                    ));
                }
                n => filled += n,
            }
        }
        match self.cipher {
            SymCipher::AesGcm { .. } => {
                self.gcm =
                    Some(Gcm::new(&self.key, &iv).map_err(|e| io::Error::other(e.to_string()))?);
            }
            SymCipher::AesCbc { .. } | SymCipher::TripleDesCbc => {
                self.cbc = Some(
                    CbcDecrypt::new(self.cipher, &self.key, &iv)
                        .map_err(|e| io::Error::other(e.to_string()))?,
                );
            }
        }
        self.iv = iv;
        self.initialized = true;
        Ok(())
    }
}

impl<R: Read> Read for DecryptReader<R> {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        if buf.is_empty() {
            return Ok(0);
        }
        self.initialize()?;
        loop {
            if self.plain_pos < self.plain.len() {
                let n = buf.len().min(self.plain.len() - self.plain_pos);
                buf[..n].copy_from_slice(&self.plain[self.plain_pos..self.plain_pos + n]);
                self.plain_pos += n;
                return Ok(n);
            }
            if self.done {
                return Ok(0);
            }

            let mut chunk = vec![0u8; 8 * 1024];
            let n = self.inner.read(&mut chunk)?;
            if n == 0 {
                self.done = true;
                if let Some(gcm) = self.gcm.take() {
                    if self.gcm_holdback.len() != GCM_TAG_LEN {
                        return Err(io::Error::other("GCM stream without tag"));
                    }
                    let expected = gcm.tag();
                    if self.gcm_holdback != expected {
                        return Err(io::Error::other("GCM tag mismatch"));
                    }
                    return Ok(0);
                }
                let cbc = self.cbc.as_mut().expect("cbc mode");
                let mut out = Vec::new();
                cbc.finish(&mut out)
                    .map_err(|e| io::Error::other(e.to_string()))?;
                self.plain = out;
                self.plain_pos = 0;
                continue;
            }

            if let Some(gcm) = self.gcm.as_mut() {
                self.gcm_holdback.extend_from_slice(&chunk[..n]);
                let ciphertext_len = self.gcm_holdback.len().saturating_sub(GCM_TAG_LEN);
                if ciphertext_len > 0 {
                    let mut data = self.gcm_holdback[..ciphertext_len].to_vec();
                    gcm.process(&mut data);
                    self.plain = data;
                    self.plain_pos = 0;
                    self.gcm_holdback.drain(..ciphertext_len);
                }
            } else {
                let cbc = self.cbc.as_mut().expect("cbc mode");
                let mut out = Vec::new();
                cbc.update(&chunk[..n], &mut out);
                self.plain = out;
                self.plain_pos = 0;
            }
        }
    }
}

/// One-shot helpers for small payloads (tests, wrapped session keys).
pub mod oneshot {
    use super::*;

    pub fn encrypt(
        cipher: SymCipher,
        key: &[u8],
        iv: &[u8],
        plaintext: &[u8],
    ) -> Result<Vec<u8>, CryptoError> {
        let mut out = Vec::with_capacity(plaintext.len() + cipher.iv_length() + GCM_TAG_LEN);
        let mut w = EncryptWriter::new(&mut out, cipher, key, Some(iv))?;
        w.write_all(plaintext)
            .map_err(|e| CryptoError::Encryption(e.to_string()))?;
        w.finish()
            .map_err(|e| CryptoError::Encryption(e.to_string()))?;
        Ok(out)
    }

    pub fn decrypt(
        cipher: SymCipher,
        key: &[u8],
        iv_and_ciphertext: &[u8],
    ) -> Result<Vec<u8>, CryptoError> {
        let mut r = DecryptReader::new(iv_and_ciphertext, cipher, key)?;
        let mut out = Vec::new();
        r.read_to_end(&mut out)
            .map_err(|e| CryptoError::Decryption(e.to_string()))?;
        Ok(out)
    }
}
